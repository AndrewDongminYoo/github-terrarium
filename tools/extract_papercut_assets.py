"""Extract named runtime pieces from the reviewed, immutable reference SVG."""

import copy
import hashlib
import xml.etree.ElementTree as ET
from pathlib import Path

REFERENCE_SHA256 = "f87b93c4b6def040906347b1ab690413f6dddd5d03112218c04941038a5264e9"


def extract(raw):
    if hashlib.sha256(raw).hexdigest() != REFERENCE_SHA256:
        raise ValueError("Reference changed; review the piece map before extraction")
    reference = ET.fromstring(raw)
    for node in reference.iter():
        node.tag = node.tag.removeprefix("{http://www.w3.org/2000/svg}")
    scene = reference.find("g")
    root = ET.Element("svg", {"xmlns": "http://www.w3.org/2000/svg"})
    root.append(
        ET.Comment(
            "Generated by tools/extract_papercut_assets.py; "
            "edit the extractor, not this file."
        )
    )
    defs = copy.deepcopy(reference.find("defs"))
    root.append(defs)

    def piece(name, children):
        group = ET.SubElement(defs, "g", {"id": name})
        for node in children:
            node = copy.deepcopy(node)
            for child in node.iter():
                child.attrib.pop("class", None)
                child.attrib.pop("style", None)
            group.append(node)

    piece("landscape", list(scene)[:17])
    piece("water", list(scene)[17:20])
    piece("pond-lilies", list(scene)[23:33])
    piece("rocks", list(scene)[33:45])
    piece("cattails", list(scene)[45:49])
    piece("fern-side", list(scene)[49:51])
    for index in range(6):
        piece(f"canopy-back-{index}", list(scene)[51 + index * 3 : 54 + index * 3])
    piece("tree-trunk", list(scene)[69:71])
    for index in range(13):
        piece(f"canopy-{index}", list(scene[71 + index]))
    for index in range(3):
        piece(f"mushroom-{index}", list(scene)[84 + index * 4 : 88 + index * 4])
    for index in range(10):
        piece(f"flower-{index}", list(scene)[96 + index * 4 : 100 + index * 4])
    piece("soil-cutaway", list(scene)[136:138])
    piece("tree-roots", list(scene)[138:140])
    piece("pebbles", list(scene)[140:142])
    piece("moss-rim", list(scene)[142:144])
    piece("ferns-front", list(scene)[144:146])
    ET.indent(root, space="  ")
    return ET.tostring(root, encoding="utf-8") + b"\n"


if __name__ == "__main__":
    repo = Path(__file__).resolve().parents[1]
    source = repo / "assets/references/terrarium-papercut-sanctuary.svg"
    output = repo / "assets/terrarium/papercut.svg"
    output.write_bytes(extract(source.read_bytes()))
